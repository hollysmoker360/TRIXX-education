// Generates the translator-facing ARB files from the runtime string catalogue.
//
// The app reads its strings from `lib/core/l10n/strings.dart` (a hand-written,
// code-generation-free catalogue). Translators work on ARB files, so this script
// derives them from that single source and can be re-run at any time:
//
//   dart run tool/generate_arb.dart
//
// It is a plain Dart script with no package imports so it runs without Flutter
// bindings. `test/arb_test.dart` fails if the ARB files drift from the
// catalogue, so this must be re-run whenever a string changes.
import 'dart:convert';
import 'dart:io';

const _cataloguePath = 'lib/core/l10n/strings.dart';
const _outputPath = 'lib/l10n';

/// Matches `'key': 'value',` and `'key': "value",`.
final _entry = RegExp(
  r"""^\s*'([A-Za-z0-9_]+)':\s*(?:'([^']*)'|"([^"]*)"),?\s*$""",
  multiLine: true,
);

/// `%name%` markers become ARB `{name}` placeholders.
final _placeholder = RegExp(r'%([A-Za-z0-9_]+)%');

Map<String, String> _parseMap(String source, String name) {
  final start = source.indexOf('const $name = <String, String>{');
  if (start < 0) {
    stderr.writeln('Could not find `const $name` in $_cataloguePath');
    exit(1);
  }
  final end = source.indexOf('\n};', start);
  if (end < 0) {
    stderr.writeln('Could not find the end of `const $name`');
    exit(1);
  }
  final values = <String, String>{};
  for (final match in _entry.allMatches(source.substring(start, end))) {
    final key = match.group(1)!;
    final value = match.group(2) ?? match.group(3) ?? '';
    if (values.containsKey(key)) {
      stderr.writeln('Duplicate string key: $key');
      exit(1);
    }
    values[key] = value;
  }
  return values;
}

Map<String, Object?> _arbFor(Map<String, String> values, String locale) {
  final arb = <String, Object?>{
    '@@locale': locale,
    '@@comment':
        'Generated by tool/generate_arb.dart from lib/core/l10n/strings.dart. '
            'Do not edit by hand: edit the catalogue and re-run the generator.',
  };
  for (final entry in values.entries) {
    final placeholders = _placeholder.allMatches(entry.value).map((m) => m.group(1)!).toSet();
    arb[entry.key] = entry.value.replaceAllMapped(
      _placeholder,
      (match) => '{${match.group(1)}}',
    );
    arb['@${entry.key}'] = placeholders.isEmpty
        ? <String, Object?>{'description': ''}
        : <String, Object?>{
            'description': '',
            'placeholders': {
              for (final name in placeholders) name: <String, Object?>{'type': 'String'},
            },
          };
  }
  return arb;
}

void main() {
  final file = File(_cataloguePath);
  if (!file.existsSync()) {
    stderr.writeln('Run this from the Flutter app directory ($_cataloguePath not found).');
    exit(1);
  }
  final source = file.readAsStringSync();
  const encoder = JsonEncoder.withIndent('  ');
  final outputs = <String, Map<String, String>>{
    'app_en.arb': _parseMap(source, '_en'),
    'app_sw.arb': _parseMap(source, '_sw'),
  };

  Directory(_outputPath).createSync(recursive: true);
  for (final output in outputs.entries) {
    final locale = output.key.split('.').first.split('_').last; // en, sw
    final arb = _arbFor(output.value, locale);
    File('$_outputPath/${output.key}').writeAsStringSync('${encoder.convert(arb)}\n');
    stdout.writeln('wrote $_outputPath/${output.key} (${output.value.length} messages)');
  }
}
